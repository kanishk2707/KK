"""Pack the tiny story model into a C header for the firmware: firmware/kanishk/model_data.h
Run:  python tools/build_assets.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'firmware', 'kanishk')


def c_bytes(data, per_line=32):
    return ',\n'.join(','.join(str(b) for b in data[i:i + per_line]) for i in range(0, len(data), per_line))


def model():
    m = open(os.path.join(ROOT, 'model', 'stories260K.bin'), 'rb').read()
    t = open(os.path.join(ROOT, 'model', 'tok512.bin'), 'rb').read()
    out = ['// Generated by tools/build_assets.py - do not edit. llama2.c stories260K (MIT) + its tokenizer.',
           '#pragma once', '#include <stdint.h>',
           f'alignas(4) static const uint8_t MODEL_BIN[{len(m)}] = {{\n{c_bytes(m)}\n}};',
           f'alignas(4) static const uint8_t TOKENIZER_BIN[{len(t)}] = {{\n{c_bytes(t)}\n}};', '']
    open(os.path.join(OUT, 'model_data.h'), 'w').write('\n'.join(out))
    print(f'model: {len(m) // 1024} KB, tokenizer: {len(t)} bytes')


if __name__ == '__main__':
    model()
